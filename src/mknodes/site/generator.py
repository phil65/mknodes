logger = log.get_logger(__name__)


def _page_url(path: str) -> str:
    """Return the directory-style URL of a page path (`a/b.md`, `a/b/index.md` -> `a/b/`)."""
    p = pathlib.PurePosixPath(path)
    stem = p.with_suffix("")
    if p.name in {"index.md", "README.md"}:
        return f"{stem.parent.as_posix()}/".removeprefix("./")
    return f"{stem.as_posix()}/"


def resolve_url_collisions(output: BuildOutput) -> None:
    """Rename pages that would end up at the same URL as another page.

    MkDocs silently lets one of the pages win (`a/b.md` vs `a/b/index.md`, e.g. a page and
    a nav with the same name), other engines refuse to build.
    The non-index page gets renamed (`a/b-1.md`) and the nav gets updated.
    This is a last-resort safety net (with a warning): API pages generated by `MkDoc`
    (mknodes >= 3.1) are nested below their module and can't collide.
    """
    owners: dict[str, str] = {}
    renames: dict[str, str] = {}
    pages = sorted(output.pages, key=lambda p: not p.endswith(("index.md", "README.md")))
    for path in pages:
        url = _page_url(path)
        if url not in owners:
            owners[url] = path
            continue
        stem = pathlib.PurePosixPath(path).with_suffix("")
        i = 1
        while _page_url(new := f"{stem}-{i}.md") in owners:
            i += 1
        logger.warning("Page %s collides with %s, renaming to %s", path, owners[url], new)
        owners[_page_url(new)] = new
        renames[path] = new
    if not renames:
        return
    output.pages = {renames.get(k, k): v for k, v in output.pages.items()}
    output.edit_paths = {renames.get(k, k): v for k, v in output.edit_paths.items()}
    output.page_resources = {renames.get(k, k): v for k, v in output.page_resources.items()}

    def rename(items: list[NavItem]) -> None:
        for item in items:
            if item.target in renames:
                item.target = renames[item.target]
            rename(item.children)

    rename(output.nav)


@contextlib.contextmanager
def use_inputs(store: InputStore) -> Iterator[None]:
    """Make given inputs store the one of the build.

    Active store for code without a node context (themes, icon helpers), and the store of
    the fallback context (nodes which are not part of the tree, like rendered examples).
    """
    from mknodes.basenodes import mknode

    fallback = mknode.get_fallback_ctx()
    old = fallback.inputs
    fallback.inputs = store
    try:
        with inputs.use_store(store):
            yield
    finally:
        fallback.inputs = old


class SiteGenerator:
    """Runs the configured build function and returns an engine-neutral `BuildOutput`."""

    def __init__(
        self, settings: GeneratorSettings, flavor: str | rendering.Renderer | None = None
    ) -> None:
        self.settings = settings
        self.flavor = flavor or settings.flavor or "material"
        self.root: mk.MkNav | None = None
        self.theme: mk.Theme | None = None

    def create_theme(self) -> mk.Theme:
        theme_cfg = self.settings.theme_config
        name = theme_cfg.get("name") or "material"
        data = {k: v for k, v in theme_cfg.items() if not isinstance(v, yamlconfig.Tagged)}
        return mk.Theme.get_theme(theme_name=name, data=data)

    def create_context(self, theme: mk.Theme) -> contexts.ProjectContext:
        site_cfg = yamlconfig.resolve(self.settings.site_config)
        repo_path = self.settings.repo_path
        return contexts.ProjectContext.for_project(
            self.settings.project_dir if repo_path == "." else repo_path,
            clone_depth=self.settings.clone_depth,
            base_url=site_cfg.get("site_url") or "",
            use_directory_urls=site_cfg.get("use_directory_urls", True),
            theme=theme.context,
            env_config=self.settings.get_jinja_config(),
            inputs=self.settings.input_store,
        )

    def generate(self) -> BuildOutput:
        """Run the build function and collect pages, nav and resources.

        Problems which don't stop the build (failed nodes, broken code fences,
        unresolved references) get logged and collected in `BuildOutput.diagnostics`.

        Setup and the build function run synchronously (nodes may
        do blocking I/O on creation), only the collection step runs in an event loop.
        """
        with diagnostics.collect() as collected, use_inputs(self.settings.input_store):
            output = self._generate()
        output.diagnostics = list(collected)
        return output

    def _generate(self) -> BuildOutput:
        theme = self.create_theme()
        ctx = self.create_context(theme)
        root = mk.MkNav(context=ctx)
        self.root, self.theme = root, theme
        logger.info("Running build function %s...", self.settings.build_fn)
        result = self.settings.get_builder()(theme=theme, root=root)
        if inspect.iscoroutine(result):
            run_sync(result)
        # Walk the tree in the target flavour: template nodes render once (for their
        # children) and reuse that render for their content.
        with rendering.use(rendering.get_renderer(self.flavor)):
            paths = [
                pathlib.Path(node.resolved_file_path).stem
                for _level, node in root.iter_nodes()
                if isinstance(node, mk.MkPage | mk.MkNav)
            ]
        ctx.links.set_excludes(paths)
        # Link output depends on the excludes: templates rendered by the walk above
        # (pages can come from templates) render again in the build.
        rendercache.invalidate_all()

        builder = DocBuilder(
            flavor=self.flavor,
            render_jinja=self.settings.render_by_default,
            show_page_info=self.settings.show_page_info,
            global_resources=self.settings.global_resources,
        )
        output = run_sync(builder.build(root, theme))
        logger.info("Inputs: %s", ", ".join(f"{k} {v}" for k, v in ctx.inputs.stats().items()))
        ctx.inputs.save()
        resolve_url_collisions(output)
        self.replace_links(output)
        self.check_references(output, root)
        return output

    def check_references(self, output: BuildOutput, root: mk.MkNav) -> list[RefIssue]:
        """Check the `[title][identifier]` references of the pages before the engine runs.

        References engines can't resolve but which point to a rendered object under
        another path (members of import aliases, inherited members) get rewritten,
        a warning gets logged for each remaining one (with page, node and the template /
        source line it comes from).

        Returns:
            The references which could not get fixed.
        """
        metadata = root.ctx.metadata
        names = metadata.package_names or [metadata.distribution_name.replace("-", "_")]
        packages = list(dict.fromkeys(name.split(".")[0] for name in names))
        issues = refcheck.check_output(
            output,
            root,
            packages=packages,
            inventory=root.ctx.links.inv_manager,
        )
        fixed = refcheck.fix_references(output, issues)
        for issue in fixed:
            logger.debug("Rewrote reference: %s", issue)
        if fixed:
            logger.info("Pointed %s references to their documented path", len(fixed))
        remaining = [i for i in issues if i not in fixed]
        for issue in remaining:
            location = f"line {issue.line}" if issue.line else None
            message = str(issue).split(": ", 1)[1]
            diagnostics.report("reference", message, page=issue.page, location=location)
        if remaining:
            logger.warning("%s unresolved references (see above)", len(remaining))
        return remaining

    def replace_links(self, output: BuildOutput) -> None:
        """Point bare `[title](file.md)` links in generated pages to the actual page path."""
        replacer = linkreplacer.LinkReplacer()
        docs_dir = self.settings.resolved_docs_dir
        existing = [p.relative_to(docs_dir).as_posix() for p in _iter_files(docs_dir)]
        for path in [*existing, *output.files]:
            name = pathlib.PurePosixPath(path).name
            url = urllib.parse.unquote(path)
            if url not in replacer.mapping[name]:
                replacer.mapping[name].append(url)
        for path, md in output.pages.items():
            if re.search(linkreplacer.AUTOLINK_RE, md):
                output.pages[path] = replacer.replace(md, path)


def _iter_files(folder: pathlib.Path):
    if not folder.is_dir():
        return
    for p in folder.rglob("*"):
        if p.is_file() and not any(part.startswith(".") for part in p.parts[-1:]):
            yield p
